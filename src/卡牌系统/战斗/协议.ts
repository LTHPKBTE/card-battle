// 战斗协议 - 注入给 AI 的固定系统提示词
//
// 纯函数, 不依赖酒馆全局, 可直接在 node 中测试.
// 与 决策.ts 的解析器严格对应: 改这里的格式就必须同步改那边的解析.

import { sanitizeForPrompt } from './简报.ts';
import { ACTION_TAG, MAX_DECISION_OPS } from './决策.ts';

/**
 * 协议版本: 改动 `protocolText()` 时必须 +1.
 *
 * 世界书条目是用户手动安装的, 版本变化后需要重新运行 `生成世界书.ts` 并让用户重新导入;
 * `checkBattleWorldbook()` 会比对条目内容, 面板据此提示「需要更新」.
 */
export const PROTOCOL_VERSION = 5;

/** 决策块的完整标签 */
export const ACTION_BLOCK_TAG = ACTION_TAG;

/** 简报的小标题 */
export const BRIEF_HEADING = '【本回合简报】';

/**
 * 双方操控模式下的提示词 (替代 protocolText).
 *
 * 玩家同时操作两边时, AI 不应该再输出决策块, 否则会和玩家的操作打架;
 * 但如果不告诉它, 它很可能因为「简报里写着敌方是你」而自作主张地行动.
 */
export function bothSidesNote(): string {
  return [
    '【卡牌战斗 · 双方操控中】',
    '本场战斗由玩家同时操作 PLAYER 与 ENEMY 两边, 双方的行动都不需要你决定。',
    '因此: 不要输出任何 battle_action 决策块, 也不要替任何一方做决定或假设自己已经行动。',
    '你只需要依据下面的简报正常叙事, 把已经发生的事讲清楚即可。',
  ].join('\n');
}

/**
 * 固定协议文本 (不含动态数据).
 *
 * 注意: 这段文字会被世界书条目读取, 所以不要包含 `{{` `}}`, 否则会被酒馆当成宏再展开一次.
 */
export function protocolText(): string {
  return [
    '【卡牌战斗 · 你的行动】',
    '你在故事中同时扮演敌方阵营 ENEMY 的战术指挥。下面的「本回合简报」是引擎给出的真实局面:',
    '只有简报里出现过的卡牌 id 才是存在的, 不要虚构卡牌、数值或效果。',
    '简报里「你」指 ENEMY (由你操作), 「对手」指 PLAYER (由玩家操作)。',
    '每张卡的数值按「攻击/护盾/生命」排列, 形如 500/300/1500; 带括号的数值是这一局被修正过的量。',
    '花括号里的内容是这些修正的来源 (哪张卡、哪个效果给的), 不要把它们当成卡牌数值。',
    '伤害默认先扣护盾, 护盾归零后的溢出部分才扣生命 (没有盾的卡盾为 0)。',
    '手牌前面写的「N费」是上场要花的能量; 简报里的「能量 x/y」就是当前能量 / 本回合上限,',
    '能量每次轮到自己行动时补满 (上限随回合数增长), 花完就要等下一次行动; 上场不花能量的卡不写费。',
    '',
    '回合结构: 一个回合 = 双方各行动一次 (先手方先动, 后手方后动; 简报里的「当前行动方」就是现在该动的一方)。',
    '轮到你时你只需完成「你自己的这次行动」, 你收手后本次行动结束, 换对手行动;',
    '只有双方都收手了才会进入「回合结算」(回合制持续伤害、持续时间流逝都在那时发生), 然后开始下一个回合。',
    '',
    '在回复的最末尾输出你的决策 (必须正好一个块, 内容是合法 JSON):',
    `<${ACTION_TAG}>{"回合":3,"操作":[{"do":"play","card":"c9"},{"do":"attack","card":"c5","target":"c21"},{"do":"activate","card":"c7","effect":"战意"}]}</${ACTION_TAG}>`,
    '',
    '操作语法 (按数组顺序依次执行):',
    `- {"do":"play","card":"卡id"}                        从你的手牌召唤到场上`,
    `- {"do":"attack","card":"卡id","target":"卡id"}      用你场上的卡攻击对手场上的卡`,
    `- {"do":"attack","card":"卡id","target":"PLAYER"}    用你场上的卡直接攻击对手玩家`,
    `- {"do":"activate","card":"卡id","effect":"效果id"}  主动发动效果`,
    `- {"do":"answer","ask":"询问id","cards":["卡id"]}  回答简报里的「需要你回答」(例如弃牌), ask 可省略`,
    `- {"do":"discard","cards":["卡id"]}                 弃手牌的简写写法 (等同上面那条, 只用来弃牌)`,
    `- {"do":"end"}                                       结束你的本次行动 (交给对手)`,
    '',
    '带标记的重要效果 (机读区写了 ask): 简报会在「需要你回答」里列出来, 你可以在操作里补一个字段',
    'answers: ["效果id"] (批准这一次发动) 或 [] (不发动); 不写这个字段就按卡上的默认 (发动 / 不发动) 处理。',
    '收手时 (结束行动) 才会触发的这类效果写在决策块最外层: {"answers":["效果id"],"操作":[...]}。',
    '规则:',
    '1. 「回合」必须等于简报里的回合数, 否则整块决策会被丢弃。',
    '2. 操作按顺序执行, 全部执行完后自动结束你的本次行动, 不需要写 end; 空数组表示什么都不做。',
    `3. 最多 ${MAX_DECISION_OPS} 条操作; 不合法的操作会被跳过 (不影响后面的), 所以只写你确实能做成的。`,
    '4. 卡牌 id 形如 c12; 玩家固定写 PLAYER / ENEMY。',
    '5. 简报里的「最近操作」是双方这回合已经做过的事, 不要重复已完成的动作。',
    '6. 简报里出现「需要你回答:」时必须先在操作里回答它 (弃牌用 discard / answer), 否则那一步会被跳过。',
    '7. 叙事部分自由发挥, 但不要编造数值与结果 —— 实际结算以引擎为准, 下一次简报会告诉你发生了什么。',
  ].join('\n');
}

/**
 * 组装最终注入给 AI 的提示词 (协议 + 简报).
 *
 * 主流程用的是「世界书条目读变量」, 这个函数留给 `injectPrompts` 备选方案使用;
 * `brief_text` 为空时返回空串, 表示不注入.
 */
export function buildPromptText(brief_text: string): string {
  const brief = sanitizeForPrompt(String(brief_text ?? '').trim());
  if (!brief) {
    return '';
  }
  return `${protocolText()}\n\n${BRIEF_HEADING}\n${brief}`;
}
